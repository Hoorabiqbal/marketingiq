"""
Conversation memory for the AI Analyst: a compact structured state per chat session, and a
deterministic resolver for follow-ups ("make this a chart", "what about February?", "now spend").

    session id (opaque, generated by the browser) -> SessionState: the last analytical request as a
    validated query_planner.Plan, plus a little metadata. No transcript, no answers, no personal text.

Follow-ups are resolved by editing the remembered plan (metric, entity, filter, period, chart type),
re-validating it with query_planner.validate_plan() and running it on the data tools: 0 LLM calls.
Only a follow-up this can't resolve goes to the analytics planner, with the compact previous plan
(never the transcript). A reference with nothing to refer to gets a clarification.

Sessions live in this process's memory, bounded in number and age: a server restart (e.g. a Render
redeploy or cold start) forgets them, and the conversation simply starts fresh.
"""
import copy
import json
import re
import threading
import time
from collections import OrderedDict, deque
from dataclasses import dataclass, field

import chart_builder as cb
import query_planner as qp
import query_router as qr
import schema_catalog as catalog
import semantic_parser

SESSION_ID_RE = re.compile(r"^[A-Za-z0-9-]{16,64}$")
MAX_SESSIONS = 2000
SESSION_TTL_S = 4 * 3600
MAX_TURNS = 6


@dataclass
class SessionState:
    plan: qp.Plan = None        # the last analytical request, validated
    question: str = None        # its wording (truncated); only analytical requests are kept
    route: str = None
    chart: dict = None          # {"type", "title"} of the last chart, no data
    turns: deque = field(default_factory=lambda: deque(maxlen=MAX_TURNS))  # {"route", "kind"}: no text
    updated: float = 0.0

    def remember(self, plan, question: str, route: str, chart: dict = None):
        self.plan, self.question, self.route = plan, (question or "")[:200], route
        self.chart = {"type": chart["type"], "title": chart["title"]} if chart else None


class SessionStore:
    """In-process, bounded (least recently used sessions are dropped first) and time-limited."""

    def __init__(self, max_sessions: int = MAX_SESSIONS, ttl_s: float = SESSION_TTL_S, clock=time.monotonic):
        self.max_sessions, self.ttl_s, self._clock = max_sessions, ttl_s, clock
        self._sessions = OrderedDict()
        self._lock = threading.Lock()

    def get(self, session_id):
        """The session's state (created on first use), or None for a missing/invalid id."""
        if not isinstance(session_id, str) or not SESSION_ID_RE.match(session_id):
            return None
        with self._lock:
            now = self._clock()
            while self._sessions:
                oldest = next(iter(self._sessions.values()))
                if now - oldest.updated <= self.ttl_s:
                    break
                self._sessions.popitem(last=False)
            state = self._sessions.pop(session_id, None) or SessionState()
            state.updated = now
            self._sessions[session_id] = state
            while len(self._sessions) > self.max_sessions:
                self._sessions.popitem(last=False)
            return state

    def __len__(self):
        return len(self._sessions)


