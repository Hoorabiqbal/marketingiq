DEFAULT_METRICS = ["revenue", "spend", "roas"]


def plan_from_router(r: dict):
    """The DIRECT_DATABASE answer as a plan, or None for answers a follow-up can't build on."""
    tool, inp = r.get("tool"), r.get("tool_input") or {}
    focus = [m for m in r.get("focus_metrics") or [] if m in qp.METRICS][:qp.MAX_METRICS]
    scope = dict(r.get("scope") or {})
    period = r.get("period")
    raw = {"intent": None, "metrics": focus or DEFAULT_METRICS, "dimension": None, "entities": [], "filters": scope,
           "months": [int(period[5:7])] if period and len(period) == 7 else [],
           "years": [int(period[:4])] if period else [], "grain": None, "conditions": [], "order": "desc",
           "limit": None, "visualization": None}
    if tool == "get_totals":
        raw["intent"] = "total"
    elif tool == "rank_dimension" and inp.get("metric") in qp.METRICS:
        raw.update(intent="breakdown", metrics=[inp["metric"]], dimension=inp["dimension"], order=inp.get("order", "desc"),
                   limit=None if inp.get("limit") in (1, 10) else inp.get("limit"))
    elif tool == "trend_over_time":
        raw.update(intent="trend", metrics=[inp.get("metric", "revenue")], grain="month")
    elif tool == "compare_entities":
        raw.update(intent="compare_entities", dimension=inp["dimension"], entities=list(inp["names"]))
    elif tool == "get_entity_metrics" and inp.get("dimension") in qr.ENTITY_FILTER_KEYS:
        raw.update(intent="total", filters={**scope, qr.ENTITY_FILTER_KEYS[inp["dimension"]]: inp["name"]})
    elif tool == "filter_campaigns":
        sort_by = inp.get("sort_by", "profit")
        raw.update(intent="campaign_list", metrics=[sort_by] if sort_by in qp.METRICS else ["profit"],
                   conditions=list(inp.get("conditions") or []), order=inp.get("order", "asc"), limit=inp.get("limit"))
    else:
        return None
    return checked_plan(raw)


def checked_plan(fields: dict):
    """Plan fields -> a validated Plan (dataset spellings, allowlists), or None."""
    try:
        plan = qp.Plan(**{k: v for k, v in fields.items() if k in qp.Plan.__dataclass_fields__})
        return qp.validate_plan(json.dumps(qp.plan_to_raw(plan)))
    except (qp.PlanError, TypeError, KeyError, ValueError):
        return None
