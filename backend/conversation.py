"""
Conversation memory for the AI Analyst: a compact structured state per chat session, plus two narrow
helpers that never build or edit an analytics plan (that is the local Qwen model's job):

    request type    analysis / explanation / advice, and whether a message only points at the
                    remembered analysis ("why?", "what should we improve?")
    follow-up       whether the remembered validated plan is sent to the model with the question

    session id (opaque, generated by the browser) -> SessionState: the last analytical request as a
    validated query_planner.Plan, plus a little metadata. No transcript, no answers, no personal text.

Sessions live in this process's memory, bounded in number and age: a server restart forgets them,
and the conversation simply starts fresh.
"""
import re
import threading
import time
from collections import OrderedDict, deque
from dataclasses import dataclass, field

import query_planner as qp
import schema_catalog as catalog

SESSION_ID_RE = re.compile(r"^[A-Za-z0-9-]{16,64}$")
MAX_SESSIONS = 2000
SESSION_TTL_S = 4 * 3600
MAX_TURNS = 6


@dataclass
class SessionState:
    plan: qp.Plan = None        # the last analytical request, validated
    question: str = None        # its wording (truncated); only analytical requests are kept
    route: str = None
    chart: dict = None          # {"type", "title"} of the last chart, no data
    campaign: str = None        # ID of the one campaign the last answer was about ("it", "this campaign")
    turns: deque = field(default_factory=lambda: deque(maxlen=MAX_TURNS))  # {"route", "kind"}: no text
    updated: float = 0.0

    def remember(self, plan, question: str, route: str, chart: dict = None):
        self.plan, self.question, self.route = plan, (question or "")[:200], route
        self.chart = {"type": chart["type"], "title": chart["title"]} if chart else None


class SessionStore:
    """In-process, bounded (least recently used sessions are dropped first) and time-limited."""

    def __init__(self, max_sessions: int = MAX_SESSIONS, ttl_s: float = SESSION_TTL_S, clock=time.monotonic):
        self.max_sessions, self.ttl_s, self._clock = max_sessions, ttl_s, clock
        self._sessions = OrderedDict()
        self._lock = threading.Lock()

    def get(self, session_id):
        """The session's state (created on first use), or None for a missing/invalid id."""
        if not isinstance(session_id, str) or not SESSION_ID_RE.match(session_id):
            return None
        with self._lock:
            now = self._clock()
            while self._sessions:
                oldest = next(iter(self._sessions.values()))
                if now - oldest.updated <= self.ttl_s:
                    break
                self._sessions.popitem(last=False)
            state = self._sessions.pop(session_id, None) or SessionState()
            state.updated = now
            self._sessions[session_id] = state
            while len(self._sessions) > self.max_sessions:
                self._sessions.popitem(last=False)
            return state

    def __len__(self):
        return len(self._sessions)


# ---------------------------------------------------------------------------
# What a message mentions (schema catalog vocabulary + the dataset's own values)
# ---------------------------------------------------------------------------

_c = lambda p: re.compile(p, re.IGNORECASE)  # noqa: E731
DATA_VOCAB_RE = _c(r"\bcampaigns?\b|\bads?\b|\badvertis|\bmarketing\b|\bperform|\btrends?\b|\bdata(?:set)?\b"
                   r"|\bresults?\b|\bnumbers\b|\bkpis?\b|\bbudget|\baudiences?\b|\bcreatives?\b")
YEAR_WORD_RE = re.compile(r"\b(20\d{2})\b")
MONTH_WORD_RE = _c(r"\b(?:january|february|march|april|june|july|august|september|october|november|december"
                   r"|jan|feb|mar|apr|jun|jul|aug|sept?|oct|nov|dec)\b")
_values = None


def _value_patterns() -> list:
    """Every listable dataset value (and "google" for "Google Ads"), as word patterns. Built once."""
    global _values
    if _values is None:
        pats = []
        for d in catalog.dimensions().values():
            for v in d.values or ():
                v = str(v).lower()
                if len(v) < 3 or v in ("all", "high", "low", "medium", "other", "text", "true", "false"):
                    continue
                alts = [re.escape(v)] + ([re.escape(v[:-4])] if v.endswith(" ads") else [])
                pats.append(re.compile(rf"(?<![\w]){'|'.join(alts)}(?![\w])"))
        _values = pats
    return _values


@dataclass
class Mentions:
    metrics: list
    dimensions: list
    entities: int
    period: bool

    @property
    def analytical(self) -> bool:
        return bool(self.metrics or self.dimensions or self.entities or self.period)


def mentions(question: str) -> Mentions:
    text = " ".join(question.lower().split())
    return Mentions([m for m in catalog.find_metrics(text) if m in qp.METRICS], catalog.find_dimensions(text),
                    sum(1 for p in _value_patterns() if p.search(text)),
                    bool(YEAR_WORD_RE.search(text) or MONTH_WORD_RE.search(text)))


# ---------------------------------------------------------------------------
# Small talk and out-of-scope personal topics (answered here, no model call, nothing remembered)
# ---------------------------------------------------------------------------

GREETING_RE = _c(r"^\W*(?:hi|hello|hey|hiya|howdy|greetings|good (?:morning|afternoon|evening))"
                 r"(?:\s+(?:there|team|again|marketingiq))?\W*$")
THANKS_RE = _c(r"^\W*(?:thanks?(?: you)?(?: so much| a lot| very much)?|thank you(?: so much| very much)?|ty|cheers"
               r"|great|awesome|perfect|cool|nice|ok(?:ay)?|got it|excellent|amazing|brilliant|wonderful)"
               r"(?:\W+(?:thanks?|thank you))?\W*$")
IDENTITY_RE = _c(r"^\W*(?:who are you|what are you|what (?:can|do) you do|what (?:can|could) you help(?: me)?(?: with)?"
                 r"|how (?:can|could|do) you help(?: me)?|help(?: me)?|what can i ask(?: you)?|what should i ask(?: you)?"
                 r"|what (?:kind of |sort of )?questions (?:can|could|should) i ask(?: you)?"
                 r"|what are your (?:capabilities|features|skills))\W*$")
PERSONAL_RE = _c(r"\b(?:marriage|married|marry|wife|husband|spouse|girlfriend|boyfriend|dating|divorce"
                 r"|relationship advice|love life|break ?up|wedding|my (?:family|kids|children|parents|mom|dad"
                 r"|mother|father|son|daughter)|lonely|depress\w*|therapy|horoscope)\b")

GREETING = ("Hi! I'm the MarketingIQ AI Analyst. Ask me about your campaign data, for example "
            "\"Show revenue by platform\" or \"Is January revenue increasing over time?\".")
THANKS = "Glad to help! What would you like to look at next?"
IDENTITY = ("I'm the MarketingIQ AI Analyst. I can analyze your campaign data, compare performance, investigate "
            "trends, apply filters, answer follow-up questions, explain results and suggest next steps, and "
            "create charts from your data. For example: \"Which platform has the highest ROAS?\", \"Compare TikTok "
            "and Google Ads revenue\" or \"Show monthly spend as a line chart\".")
PERSONAL = ("I'm sorry, I can't help with that. I'm MarketingIQ's analyst, so I only work with the campaign "
            "dataset. I'd be glad to help with a question like \"Which platform has the best ROAS?\".")


def small_talk(question: str):
    """(kind, reply) for greetings, thanks, "who are you" and personal off-topic messages; else None."""
    text = question.strip()
    if GREETING_RE.match(text):
        return "greeting", GREETING
    if THANKS_RE.match(text):
        return "thanks", THANKS
    if IDENTITY_RE.match(text):
        return "identity", IDENTITY
    if PERSONAL_RE.search(text) and not (DATA_VOCAB_RE.search(text) or mentions(text).analytical):
        return "personal", PERSONAL
    return None


# ---------------------------------------------------------------------------
# Request type: what kind of answer the user wants (the model still decides what to analyze)
# ---------------------------------------------------------------------------

EXPLAIN_RE = _c(r"\b(?:why|how come|explain\w*|reasons?|interpret\w*|insights?|drivers?)\b"
                r"|\bwhat(?:'s| is| are) (?:driving|behind|causing)\b|\bwhat (?:does|do) (?:this|that|it|these|those)(?: \w+)? mean\b")
ADVICE_RE = _c(r"\b(?:recommend\w*|suggest\w*|advice|advise|action plan|next steps?|what actions?"
               r"|what (?:should|can|could) (?:we|i) do|what should (?:we|i)"
               r"|(?:how|ways?) (?:can|could|should|do|would|to) (?:we |i )?(?:improve|increase|boost|grow|raise"
               r"|optimi[sz]e|reduce|lower|fix|scale|reallocate)|be improved|optimi[sz]e"
               r"|should (?:get|receive|have) (?:more|less) (?:budget|spend)|reallocat\w*|budget allocation"
               r"|where (?:should|to) (?:we |i )?(?:invest|spend|put)"
               r"|how (?:can|could|should|would|might|to)(?:\s+[\w-]+){1,4}\s+(?:improve|become (?:successful|profitable)"
               r"|turn around|recover))\b")
# The framing around an analytical question ("Why is ...", "How can we improve ...", "What should we do
# about ..."), dropped before planning: the model was trained on analytical questions, not on framing.
FRAME_RE = _c(r"^\W*(?:why\s+(?:is|are|was|were|does|do|did|has|have)\s+|how come\s+|explain\s+(?:why|how)?\s*"
              r"|what(?:'s| is| are) (?:driving|behind|causing)\s+"
              r"|how (?:can|could|should|do|would) (?:we|i) (?:improve|increase|boost|grow|raise|reduce|lower|cut|fix"
              r"|optimi[sz]e|reallocate)\s+"
              r"|what should (?:we|i) do (?:about|with|for)\s+|what should (?:we|i) (?:change|improve) (?:on|in|for)\s+"
              r"|(?:please\s+)?(?:recommend|suggest)\s+(?:actions\s+)?(?:for|on)\s+)")
INTENSIFIER_RE = _c(r"\b(?:such an?|so|very|really|too|that)\s+(?=(?:low|high|weak|strong|poor|bad|good|small|large)\b)")
COMPARATIVES = {"weaker": "weakest", "stronger": "strongest", "worse": "worst", "poorer": "poorest"}


def request_kind(question: str) -> str:
    """"advice", "explanation" or "analysis"."""
    if ADVICE_RE.search(question):
        return "advice"
    if EXPLAIN_RE.search(question):
        return "explanation"
    return "analysis"


FILLER_RE = _c(r"\b(?:why|how|come|what|which|explain\w*|interpret\w*|should|can|could|would|we|i|you|do|does|did|is"
               r"|are|was|were|it|its|this|that|these|those|the|a|an|to|about|on|in|for|with|of|me|us|our|my|improve"
               r"|change|fix|optimi[sz]e|next|steps?|recommend\w*|suggest\w*|advice|actions?|results?|answer|numbers"
               r"|figures|data|please|so|then|now|there|here|happen\w*|mean|means|drives?|driving|behind|reasons?|any|some)\b")


def about_previous(question: str) -> bool:
    """An explanation / advice request about the remembered analysis ("Why?", "Explain this", "What should
    we improve?", "What do these results mean?"): it names nothing to analyze, and it either points back
    or has nothing left but framing."""
    if mentions(question).analytical:
        return False
    rest = re.sub(r"[^\w\s-]", " ", FILLER_RE.sub(" ", question.lower())).split()
    return bool(REFERENCE_RE.search(question)) or not rest


def analysis_question(question: str) -> str:
    """The analytical part of an explanation / advice request, for the planner ("Why is TikTok ROAS
    lower than Google Ads?" -> "TikTok ROAS lower than Google Ads")."""
    q = FRAME_RE.sub("", question.strip(), count=1)
    q = INTENSIFIER_RE.sub("", q)
    q = re.sub(r"\b(" + "|".join(COMPARATIVES) + r")\b", lambda m: COMPARATIVES[m.group(1).lower()], q, flags=re.I)
    q = q.strip().rstrip("?").strip()
    return q or question


# ---------------------------------------------------------------------------
# Follow-ups: does this message continue the remembered analysis?
# ---------------------------------------------------------------------------

NO_CONTEXT = ("I don't have an earlier result in this conversation to refer to. What would you like to look at? "
              "For example: \"Revenue by platform\" or \"Monthly spend for TikTok\".")
REFERENCE_RE = _c(r"\b(?:this|that|those|these|it|its|them|same|again|instead|previous|above|earlier)\b")
LEAD_RE = _c(r"^\W*(?:and|also|now|then|so|ok(?:ay)?|what about|how about|what if|make|turn|convert|change|switch"
             r"|use|try|redo|show (?:it|that|this|them|the same|me that))\b")
CHART_WORD_RE = _c(r"\b(?:charts?|graphs?|plot|visuali[sz]\w*|diagram|pie|donut|bars?|lines?|columns?)\b")
TRANSFORM_RE = _c(r"\b(?:top|bottom|first|last)\s+\d{1,3}\b|\b(?:lowest|highest|smallest|largest|best|worst) first\b"
                  r"|\b(?:ascending|descending)\b|\breverse (?:the )?order\b"
                  r"|\b(?:remove|without|exclude|excluding|except|drop|minus|leave out|hide)\b"
                  r"|\b(?:all|every|each)\s+(?:the\s+)?\w+s\b|\b(?:break|split)\w*\s+(?:\w+\s+)?(?:down\s+)?(?:by|across|per|into)\b"
                  r"|\bmonthly\b|\bby month\b|\bover time\b|\byearly\b|\bby year\b")
TREND_RE = _c(r"\bmonthly\b|\bby month\b|\bper month\b|\bover time\b|\btrends?\b|\bmonth[- ](?:over|by)[- ]month\b")
SELF_CONTAINED_RE = _c(r"\bcampaigns?\b|\btotal\b|\boverall\b|\ball campaigns\b|\bentire\b")


def is_follow_up(question: str, plan) -> bool:
    """True when the message continues the remembered analysis ("now profit", "chart this", "what about
    spend?", "TikTok only", "top 3"): the model then gets that validated plan with the question. A
    complete new request ("TikTok revenue in 2025", "revenue by device") is planned on its own."""
    if plan is None:
        return False
    text = " ".join(question.lower().split())
    if REFERENCE_RE.search(text) or LEAD_RE.search(text):
        return True
    m = mentions(text)
    if m.metrics and (m.dimensions or m.entities >= 2 or SELF_CONTAINED_RE.search(text) or TREND_RE.search(text)):
        return False  # names its own metric and what to break it down by / compare
    short = len(text.split()) <= 6
    return short and bool(TRANSFORM_RE.search(text) or CHART_WORD_RE.search(text) or not m.metrics)
